let idCounter = 301;
// Generate all 216 Uyir-Mei characters
meiBase.forEach((mei, mIdx) => {
  uyirSuffixes.forEach((suffix, sIdx) => {
    const char = mei + suffix;
    tamilPhonicsData.uyirMei.push({
      id: idCounter++,
      letter: char,
      syllableText: char,
      wordText: char,
      complexWord: char,
      image: `https://placehold.co/300x300/ffffff/000000?text=${char}`,
      color: colors[(mIdx + sIdx) % colors.length],
    });
  });
});

export const getPhonicsData = (lang, category = "uyir") => {
  if (lang === "en") return englishPhonicsData;
  if (lang === "ta") return tamilPhonicsData[category] || tamilPhonicsData.uyir;
  return englishPhonicsData;
};
